export function keyboardRowsFor(script, layout) {
  if (layout === 'classic') {
    const classic = CLASSIC_ROWS[script.meta.id];
    if (classic) return classic;
  }
  return alphabeticRows(script);
}

export function hasClassicKeyboard(scriptId) {
  return Boolean(CLASSIC_ROWS[scriptId]);
}

export function nextKeyboardLayout(current) {
  const i = KEYBOARD_LAYOUTS.indexOf(current);
  return KEYBOARD_LAYOUTS[(i + 1) % KEYBOARD_LAYOUTS.length];
}

function alphabeticRows(script) {
  return script.keyboardRows && script.keyboardRows.length
    ? script.keyboardRows
    : [script.letters.map(l => (l.glyph || '').split(' ')[0])];
}
